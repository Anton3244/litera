/**
 * Орнамент між секціями. Тягнеться на всю ширину контейнера.
 * @param {number} variant 0..2
 */
export function divider(variant = 0) {
  const n = ((variant % DIVIDERS.length) + DIVIDERS.length) % DIVIDERS.length;
  // Лінії обабіч — це CSS-смужки, а не частина малюнка: інакше вони або
  // тягнуться, або не дістають до країв, залежно від ширини екрана.
  return `<div class="vytynanka" aria-hidden="true">
    <i class="vytynanka__line"></i>
    <svg class="vytynanka__art" viewBox="260 0 120 54" width="86" height="34">
      <g fill="var(--accent)" color="var(--accent)">${DIVIDERS[n]}</g>
    </svg>
    <i class="vytynanka__line"></i>
  </div>`;
}

/* ---------- буквиця ---------- */

/**
 * Перша літера цитати в рамці, як у старих виданнях.
 * Викликати тільки з одним символом: решту тексту верстає той, хто кличе.
 */
export function dropCap(letter) {
  const ch = String(letter || '').trim().slice(0, 1).toUpperCase();
  if (!ch) return '';
  return `<svg class="dropcap" width="60" height="60" viewBox="0 0 74 74" aria-hidden="true">
    <rect x="1" y="1" width="72" height="72" rx="10"
      fill="var(--bg-elev-2)" stroke="var(--accent)" stroke-width="2"/>
    <path d="M10 10h8M10 10v8M64 10h-8M64 10v8M10 64h8M10 64v-8M64 64h-8M64 64v-8"
      stroke="var(--accent-2)" stroke-width="2" fill="none" stroke-linecap="round"/>
    <text x="37" y="52" text-anchor="middle" fill="var(--accent)"
      font-size="42" font-weight="800" font-family="Georgia, serif">${ch}</text>
  </svg>`;
}
